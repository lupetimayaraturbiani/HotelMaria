
    create table adocoes (
        data_solicitacao timestamp(6),
        id bigint generated by default as identity,
        pet_id bigint,
        usuario_id bigint,
        status enum ('APROVADA','PENDENTE','RECUSADA'),
        primary key (id)
    );

    create table pets (
        adotado boolean,
        idade integer,
        id bigint generated by default as identity,
        historia varchar(2000),
        foto_url varchar(255),
        genero varchar(255),
        nome varchar(255),
        raca varchar(255),
        primary key (id)
    );

    create table usuarios (
        id bigint generated by default as identity,
        email varchar(255) unique,
        endereco varchar(255),
        nome varchar(255) not null,
        senha varchar(255),
        telefone varchar(255),
        primary key (id)
    );

